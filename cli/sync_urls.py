PROTECTED_URL_APPS = {"superusers"}
EXCLUDED_DIRS = {
    "migrations", "tests", "utils", "validators", "serializers",
    "selectors", "services", "permissions", "middleware", "listeners",
    "interfaces", "forms", "filters", "exceptions", "dtos", "presenters",
    "signals", "tasks", "templates", "views", "__pycache__", "management", "models", "docs",
}


def extract_views_via_ast(sub_app_path: Path) -> list[tuple[str, str]]:
    target_files = []
    if (sub_app_path / "views.py").exists():
        target_files.append(sub_app_path / "views.py")
    if (sub_app_path / "views").is_dir():
        target_files.extend(
            py for py in sorted((sub_app_path / "views").rglob("*.py"))
            if py.name != "__init__.py" and not py.name.startswith("_")
        )

    extracted, seen = [], set()
    for py_file in target_files:
        try:
            tree = ast.parse(py_file.read_text(encoding="utf-8"), filename=str(py_file))
        except (SyntaxError, UnicodeDecodeError):
            continue

        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
                args = [a.arg for a in node.args.args]
                if args and args[0] == "request" and node.name not in seen:
                    extracted.append((node.name, "function"))
                    seen.add(node.name)
            elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
                base_str = " ".join(ast.unparse(b) for b in node.bases) if hasattr(ast, "unparse") else ""
                if "ViewSet" in node.name or "ViewSet" in base_str:
                    continue
                if any(k in node.name or k in base_str for k in ("View", "APIView")) and node.name not in seen:
                    extracted.append((node.name, "class"))
                    seen.add(node.name)
    return extracted


def generate_clean_slug(view_name: str) -> str:
    name = view_name
    for suffix in ("_view", "View", "_View"):
        if name.endswith(suffix):
            name = name[:-len(suffix)]
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower().replace("_", "-").strip("-") or view_name.lower()


def build_subapp_urls_content(sub_path: Path) -> tuple[str, int]:
    views_found = extract_views_via_ast(sub_path)
    lines = [
        "# Auto-generated by safe cli/sync_urls.py\n",
        "from django.urls import path\n",
        "from . import views\n\n",
        f"app_name = '{sub_path.name}'\n\n",
        "urlpatterns = [\n",
    ]
    for view_name, v_type in views_found:
        slug = generate_clean_slug(view_name)
        expr = f"views.{view_name}.as_view()" if v_type == "class" else f"views.{view_name}"
        lines.append(f"    path('{slug}/', {expr}, name='{slug.replace('-', '_')}'),\n")
    lines.append("]\n")
    return "".join(lines), len(views_found)


def run_safe_url_sync():
    print("=" * 70)
    print("   HYBRID MARKETPLACE - SAFE URL SYNC (Dry-Run + Backup)")
    print("=" * 70)

    dry_run = ask_dry_run(default_yes=True)
    docs_dir = ensure_documents_dir()
    audit_file = docs_dir / "sync_urls_audit.json"
    backup_root = None if dry_run else create_backup_root("urls_backup")

    records = []
    for group_dir in sorted(APPS_DIR.iterdir()):
        if not group_dir.is_dir() or group_dir.name.startswith("_"):
            continue
        for sub_dir in sorted(group_dir.iterdir()):
            if not sub_dir.is_dir() or sub_dir.name in EXCLUDED_DIRS or sub_dir.name.startswith("_"):
                continue

            sub_urls = sub_dir / "urls.py"
            if sub_dir.name in PROTECTED_URL_APPS and sub_urls.exists():
                print(f"  [PROTECTED] Skipped {group_dir.name}/{sub_dir.name}/urls.py")
                continue

            content, count = build_subapp_urls_content(sub_dir)
            if dry_run:
                print(f"  [DRY-RUN] {group_dir.name}/{sub_dir.name}/urls.py -> {count} route(s)")
            else:
                backup_file(sub_urls, backup_root)
                sub_urls.write_text(content, encoding="utf-8")
                print(f"  [UPDATED] {group_dir.name}/{sub_dir.name}/urls.py -> {count} route(s)")
            records.append({"app": f"{group_dir.name}/{sub_dir.name}", "routes": count})

    audit_file.write_text(json.dumps({"timestamp": datetime.now().isoformat(), "dry_run": dry_run, "records": records}, indent=4), encoding="utf-8")
    print(f"\nSaved: {audit_file.relative_to(PROJECT_ROOT)}")
    if backup_root:
        print(f"Backup: {backup_root.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    run_safe_url_sync()
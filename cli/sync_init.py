def ensure_tier9_documentation():
    """Ensures Tier-9 documentation is intact before starting package analysis."""
    TIER9_DOC_DIR.mkdir(parents=True, exist_ok=True)
    if not TIER_DOC_FILE.exists():
        TIER_DOC_FILE.write_text(TIER_DOC_CONTENT, encoding='utf-8')
        print(f"📘 [Tier-9 Initialized] Standard architecture map created at: {TIER_DOC_FILE.relative_to(TIER1_ROOT)}")

def parse_tier7_ast(file_path: Path) -> tuple[list[str], list[str]]:
    """Scans Tier-7 Leaf Files using AST to extract public classes and functions."""
    try:
        source = file_path.read_text(encoding='utf-8')
        tree = ast.parse(source, filename=str(file_path))
    except (SyntaxError, UnicodeDecodeError):
        return [], []

    classes, functions = [], []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith('_'):
            classes.append(node.name)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith('_'):
            functions.append(node.name)
    return sorted(classes), sorted(functions)

def sync_tier5_package(package_dir: Path, dry_run: bool = False) -> dict:
    """Synchronizes Tier-5/6 packages with Tier-7/8 leaf files and logs telemetry to Tier-9."""
    py_files = sorted(
        f for f in package_dir.glob('*.py')
        if f.name != '__init__.py' and not f.name.startswith('_')
    )
    init_file = package_dir / '__init__.py'
    rel_path = str(init_file.relative_to(TIER1_ROOT))

    if not py_files:
        if not init_file.exists() and not dry_run:
            init_file.write_text("# Auto-initialized package\n", encoding='utf-8')
            return {'updated': True, 'file': rel_path, 'exports_count': 0}
        return {'updated': False, 'exports_count': 0}

    import_lines = [
        "# ======================================================================\n",
        "# Auto-generated by 9-Tier Enterprise cli/sync_init.py (Tier 7-8 -> Tier-5)\n",
        "# ======================================================================\n\n"
    ]
    all_exports = []

    for py_file in py_files:
        classes, functions = parse_tier7_ast(py_file)
        symbols = classes + functions
        if symbols:
            import_lines.append(f"from .{py_file.stem} import {', '.join(symbols)}\n")
            all_exports.extend(symbols)

    if not all_exports:
        return {'updated': False, 'exports_count': 0}

    all_exports = sorted(list(set(all_exports)))
    import_lines.append(f"\n__all__ = {all_exports!r}\n")
    new_content = "".join(import_lines)

    old_content = init_file.read_text(encoding='utf-8') if init_file.exists() else ""
    if old_content == new_content:
        return {'updated': False, 'exports_count': len(all_exports)}

    if not dry_run:
        init_file.write_text(new_content, encoding='utf-8')
        print(f"  [✔️ Tier-5/6 Updated] {rel_path} ({len(all_exports)} symbols)")

    return {'updated': True, 'file': rel_path, 'exports_count': len(all_exports)}

def run_9tier_init_sync():
    print("\n" + "=" * 70)
    print("   HYBRID MARKETPLACE — 9-TIER cli/sync_init.py (Tier-9 to Tier-1)   ")
    print("=" * 70)

    # Step 1: Initialize Tier-9 Documentation & Standards
    ensure_tier9_documentation()

    if not TIER2_APPS.exists():
        print(f"❌ Error: Tier-2 directory '{TIER2_APPS}' not found.")
        return

    group_apps = sorted([d.name for d in TIER2_APPS.iterdir() if d.is_dir() and not d.name.startswith('_')])

    print("\n📂 [Tier-3] Available Group Apps:")
    for idx, app in enumerate(group_apps, 1):
        print(f"  [{idx}] 📂 {app}")

    choice = input("\n👉 Enter Tier-3 Group App number(s) (e.g., 1 or 1,3, or press Enter for ALL): ").strip()
    if choice:
        indices = [int(x.strip()) - 1 for x in choice.split(',') if x.strip().isdigit()]
        chosen_groups = [group_apps[i] for i in indices if 0 <= i < len(group_apps)]
    else:
        chosen_groups = group_apps

    if not chosen_groups:
        print("❌ Invalid selection. Exiting.")
        return

    dry_run = input("▶ Run in Dry-Run preview mode first? (y/n): ").strip().lower() == 'y'

    target_dirs = []
    for group in chosen_groups:
        group_path = TIER2_APPS / group
        for root, dirs, _ in os.walk(group_path):
            dirs[:] = [d for d in dirs if d not in {'migrations', '__pycache__', 'tests', '.pytest_cache'}]
            curr_path = Path(root)
            if curr_path.name in TIER5_TARGET_PACKAGES:
                target_dirs.append(curr_path)

    print(f"\n🔍 Parsing Tier-7/8 Leaf Files and updating Tier-5/6 packages...\n")
    updated_items = []

    with ThreadPoolExecutor(max_workers=6) as executor:
        futures = {executor.submit(sync_tier5_package, p, dry_run): p for p in target_dirs}
        for future in as_completed(futures):
            res = future.result()
            if res.get('updated'):
                updated_items.append(res)

    # Step 9: Save Telemetry & Audit Logs back to Tier-9
    if not dry_run and updated_items:
        TIER9_LOGS_DIR.mkdir(parents=True, exist_ok=True)
        audit_payload = {
            'timestamp': datetime.now().isoformat(),
            'flow': 'Tier-9 through Tier-1 (Bottom-Up AST Sync)',
            'updated_count': len(updated_items),
            'changes': updated_items
        }
        AUDIT_LOG_FILE.write_text(json.dumps(audit_payload, indent=4), encoding='utf-8')
        print(f"\n📁 [Tier-9 Telemetry] Audit logged to: {AUDIT_LOG_FILE.relative_to(TIER1_ROOT)}")

    print("\n" + "=" * 70)
    print("✨ 9-TIER INIT SYNC COMPLETE SUCCESSFULLY!")
    print("=" * 70 + "\n")

if __name__ == '__main__':
    run_9tier_init_sync()
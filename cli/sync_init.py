def parse_ast(file_path: Path) -> tuple[list[str], list[str]]:
    try:
        tree = ast.parse(file_path.read_text(encoding="utf-8"), filename=str(file_path))
    except (SyntaxError, UnicodeDecodeError):
        return [], []
    classes = [n.name for n in tree.body if isinstance(n, ast.ClassDef) and not n.name.startswith("_")]
    funcs = [n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_")]
    return sorted(classes), sorted(funcs)


def sync_package(package_dir: Path, dry_run: bool) -> dict:
    py_files = sorted(f for f in package_dir.glob("*.py") if f.name != "__init__.py" and not f.name.startswith("_"))
    init_file = package_dir / "__init__.py"
    rel_path = str(init_file.relative_to(PROJECT_ROOT))

    if not py_files:
        if not init_file.exists() and not dry_run:
            init_file.write_text("# Auto-initialized package\n", encoding="utf-8")
            return {"updated": True, "file": rel_path, "exports_count": 0}
        return {"updated": False, "exports_count": 0}

    lines = ["# Auto-generated by cli/sync_init.py\n\n"]
    all_exports = []
    for py_file in py_files:
        classes, funcs = parse_ast(py_file)
        symbols = classes + funcs
        if symbols:
            lines.append(f"from .{py_file.stem} import {', '.join(symbols)}\n")
            all_exports.extend(symbols)

    if not all_exports:
        return {"updated": False, "exports_count": 0}

    all_exports = sorted(set(all_exports))
    lines.append(f"\n__all__ = {all_exports!r}\n")
    new_content = "".join(lines)

    if init_file.exists() and init_file.read_text(encoding="utf-8") == new_content:
        return {"updated": False, "exports_count": len(all_exports)}

    if not dry_run:
        init_file.write_text(new_content, encoding="utf-8")
        print(f"  [UPDATED] {rel_path} ({len(all_exports)} symbols)")
    else:
        print(f"  [DRY-RUN] {rel_path} ({len(all_exports)} symbols)")

    return {"updated": True, "file": rel_path, "exports_count": len(all_exports)}


def run_9tier_init_sync():
    print("=" * 70)
    print("   HYBRID MARKETPLACE - SAFE INIT SYNC (Dry-Run + documents/)")
    print("=" * 70)

    docs_dir = ensure_documents_dir()
    arch_file = docs_dir / "ARCHITECTURE_TIERS.md"
    audit_file = docs_dir / "sync_init_audit.json"
    if not arch_file.exists():
        arch_file.write_text(ARCH_DOC_CONTENT, encoding="utf-8")

    dry_run = ask_dry_run(default_yes=True)
    target_dirs = []
    for root, dirs, _ in os.walk(APPS_DIR):
        dirs[:] = [d for d in dirs if d not in {"migrations", "__pycache__", "tests", ".pytest_cache"}]
        curr = Path(root)
        if curr.name in TARGET_PACKAGES:
            target_dirs.append(curr)

    updated = []
    with ThreadPoolExecutor(max_workers=6) as executor:
        futures = [executor.submit(sync_package, p, dry_run) for p in target_dirs]
        for fut in as_completed(futures):
            res = fut.result()
            if res.get("updated"):
                updated.append(res)

    audit_file.write_text(json.dumps({"timestamp": datetime.now().isoformat(), "dry_run": dry_run, "changes": updated}, indent=4), encoding="utf-8")
    print(f"\nSaved: {audit_file.relative_to(PROJECT_ROOT)} ({len(updated)} package(s))")


if __name__ == "__main__":
    run_9tier_init_sync()